#!/usr/bin/env bash
# Tải bản PDF đề cương HSK 3.0 (2025-11) về thư mục data_source/ (đã .gitignore)
# và ghi checksum SHA-256 vào docs/syllabus_checksums.txt.
# KHÔNG commit file PDF: quyền phân phối lại thuộc về đơn vị phát hành.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p data_source
URL="https://hsk.cn-bj.ufileos.com/3.0/%E6%96%B0%E7%89%88HSK%E8%80%83%E8%AF%95%E5%A4%A7%E7%BA%B21219.pdf"
OUT="data_source/HSK_syllabus_2025-11_1219.pdf"
curl -fL --retry 3 -o "$OUT" "$URL"
head -c 5 "$OUT" | grep -q '%PDF' || { echo "LỖI: file tải về không phải PDF"; exit 1; }
SUM=$(sha256sum "$OUT" | cut -d' ' -f1)
SIZE=$(wc -c < "$OUT")
NOW=$(date -u +%Y-%m-%dT%H:%M:%SZ)
{
  echo "# Syllabus source checksums (generated by tools/fetch_syllabus.sh)"
  echo "retrieved_at: $NOW"
  echo "url: $URL"
  echo "file: $OUT"
  echo "size_bytes: $SIZE"
  echo "sha256: $SUM"
} > docs/syllabus_checksums.txt
cat docs/syllabus_checksums.txt
